export function humanizeBehaviorType(type: string): EditorBehaviorMeta {
    return (
        EDITOR_BEHAVIOR_MAP[type] ?? {
            label: type.replace(/_/g, " "),
            tooltip: "Событие зафиксировано в редакторе и учитывается в аналитике обучения.",
        }
    );
}
